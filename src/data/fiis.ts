function defaultsForType(type: FIIType): { dy: number; div: number; price: number; score: number; consist: number; vol: number } {
  switch (type) {
    case "papel":
      return { dy: 11.5, div: 0.85, price: 90, score: 7.5, consist: 8.0, vol: 4.0 };
    case "tijolo":
      return { dy: 8.5, div: 0.65, price: 95, score: 7.5, consist: 8.0, vol: 4.0 };
    case "hibrido":
      return { dy: 9.5, div: 0.55, price: 80, score: 7.5, consist: 8.0, vol: 4.2 };
  }
}

function buildExtras(): FII[] {
  const have = new Set(CURATED.map((f) => f.ticker));
  return EXTRA_TICKERS.filter((e) => !have.has(e.ticker)).map((e) => {
    const type = e.type ?? "hibrido";
    const d = defaultsForType(type);
    return {
      ticker: e.ticker,
      name: e.name ?? e.ticker,
      type,
      segment: e.segment ?? "FII",
      price: d.price,
      dividendYield: d.dy,
      lastDividend: d.div,
      score: d.score,
      consistency: d.consist,
      volatility: d.vol,
    };
  });
}

export const FIIS: FII[] = [...CURATED, ...buildExtras()].sort((a, b) =>
  a.ticker.localeCompare(b.ticker)
);

export function getFII(ticker: string): FII | undefined {
  return FIIS.find((f) => f.ticker === ticker.toUpperCase());
}

